"""Retrieval metrics, computed from the ranked list and nothing else.

## Why this file exists at all

Before it, the harness recorded one retrieval field: `retrieval_hit`, a
bool meaning "a chunk from an expected document appeared somewhere in
the ranked list". That is too coarse to act on in both directions.

  * It cannot tell rank 1 from rank 47. Both are `True`, and only one
    of them survives `RERANK_TOP_N = 8` into the prompt. A change that
    moved every right answer from rank 2 to rank 30 would not move the
    number at all.
  * It cannot tell a retrieval failure from a generation failure. When
    an answer is wrong, "was the support even retrieved?" is the first
    question, and the only honest ways to answer it are a recall figure
    at the k the prompt actually uses and the rank the support landed
    at.

So: recall@k, MRR, and page correctness, each a pure function over a
ranked list of (document, page) pairs. No DB, no model, no answer text.

## What counts as relevant

The golden set labels support as `expect_documents` x `expect_pages` --
a filename and a page number -- NOT a chunk id. That is deliberate and
it constrains what can be measured here.

Chunk ids are generated at ingestion. They change every time the corpus
is re-ingested, every time `CHILD_TOKENS` changes, and every time the
chunker is touched. A golden set pinned to chunk ids would be invalid
after any of those, and worse, it would be invalid SILENTLY -- a stale
id matches nothing, recall reads 0.0, and the obvious conclusion is
that retrieval broke.

A (document, page) pair is stable against all three: it is a property
of the source document, which is checked into git and regenerated by
script. The loader already verifies the support really is on the named
page, so the label cannot drift away from the corpus either.

The cost of that choice, stated rather than discovered: on a page that
chunks into several children, retrieving ANY child of that page counts
as a hit even if it is not the child containing the sentence. For a
one-page-per-chunk corpus the two definitions coincide; for the 4-page
PDFs here a page is 2-6 children, so recall@k is measured slightly
optimistically. `spans_two_chunks` cases are the ones where this is
most visible, and the chunker test
(`test_spans_two_chunks_cases_really_span_two_chunks`) is what keeps
them honest about the child boundary.

## Why recall@k is a SET question and MRR is a RANK question

They answer different operational questions and must not be collapsed
into one score:

  * recall@k: "did the prompt contain the support?" k is
    `RERANK_TOP_N`, because that is what is sent to the model. Below k
    the answer cannot be grounded no matter how good the model is.
  * MRR: "how close to the top?" This is the one that moves when a
    reranker is swapped or a threshold is retuned, and it moves before
    recall does -- support sliding from rank 1 to rank 7 is invisible
    to recall@8 and is exactly the degradation worth catching early.

A single blended retrieval score would average a system that always
retrieves at rank 8 with one that retrieves at rank 1 half the time and
not at all the other half. Those are not the same system.
"""
from dataclasses import dataclass, field
from typing import Iterable, Optional, Sequence


@dataclass(frozen=True)
class RankedItem:
    """One entry in a ranked retrieval list, in rank order.

    `chunk_id` is carried for the report (a reader tracing a case wants
    the id) but is never what relevance is decided on -- see the module
    docstring.
    """

    document: str
    page: Optional[int]
    chunk_id: Optional[str] = None


@dataclass(frozen=True)
class RetrievalTarget:
    """What a case says its support is."""

    documents: tuple[str, ...] = ()
    pages: tuple[int, ...] = ()

    @property
    def is_empty(self) -> bool:
        return not self.documents


def is_relevant(item: RankedItem, target: RetrievalTarget) -> bool:
    """Does this ranked item point at labelled support?

    A page label NARROWS a document label; it never stands alone. A case
    that names pages but not documents would otherwise match page 2 of
    any document in the tenant, which is not what "page 2" means in a
    label that sits next to a filename.

    When a case names documents but no pages, every page of those
    documents counts -- correct for `.md` corpora, which have no page
    concept and are ingested as a single synthetic page.
    """
    if item.document not in target.documents:
        return False
    if not target.pages:
        return True
    return item.page in target.pages


def recall_at_k(
    ranked: Sequence[RankedItem], target: RetrievalTarget, k: int
) -> Optional[float]:
    """Fraction of labelled (document, page) units found in the top k.

    Returns None, never 0.0, when the case labels no support. An
    unanswerable question has nothing to retrieve, so "recall" is
    undefined for it -- and averaging a 0.0 in would make a correctly
    refused question look like a retrieval failure, which would push the
    metric in the direction of answering everything.

    Fraction, not a bool, because a `synthesis` case names two pages and
    needs both: finding one of them is half the support and reporting it
    as a hit hides the half that is missing.
    """
    if target.is_empty:
        return None
    if k <= 0:
        return 0.0

    units = _labelled_units(target)
    if not units:
        return None

    found = set()
    for item in ranked[:k]:
        if is_relevant(item, target):
            found.add(_unit(item, target))
    return len(found & units) / len(units)


def _labelled_units(target: RetrievalTarget) -> set:
    """The distinct things that must be retrieved.

    With pages: one unit per (document, page). Without: one per
    document.
    """
    if target.pages:
        return {(d, p) for d in target.documents for p in target.pages}
    return {(d, None) for d in target.documents}


def _unit(item: RankedItem, target: RetrievalTarget):
    return (item.document, item.page if target.pages else None)


def first_relevant_rank(
    ranked: Sequence[RankedItem], target: RetrievalTarget
) -> Optional[int]:
    """1-based rank of the first relevant item, or None if there is none."""
    if target.is_empty:
        return None
    for index, item in enumerate(ranked, start=1):
        if is_relevant(item, target):
            return index
    return None


def reciprocal_rank(
    ranked: Sequence[RankedItem], target: RetrievalTarget
) -> Optional[float]:
    """1/rank of the first relevant item.

    0.0 when support exists but was never retrieved -- that is a real
    zero and belongs in the mean. None only when the case labels no
    support at all, which is a different statement and must not be
    averaged.
    """
    if target.is_empty:
        return None
    rank = first_relevant_rank(ranked, target)
    return 0.0 if rank is None else 1.0 / rank


def mean_reciprocal_rank(values: Iterable[Optional[float]]) -> Optional[float]:
    """Mean over the cases that HAVE a reciprocal rank.

    Nones are dropped, not treated as zero. Mixing "no support to find"
    into a mean of "how well was support found" produces a number that
    drops when unanswerable cases are added to the set -- a metric that
    punishes making the golden set harder is worse than no metric.
    """
    present = [v for v in values if v is not None]
    if not present:
        return None
    return sum(present) / len(present)


def citation_pages_correct(
    cited_pages: Sequence[Optional[int]], expect_pages: Sequence[int]
) -> Optional[bool]:
    """Did the citations land on every expected page?

    Separate from recall on purpose. Recall asks what RETRIEVAL found;
    this asks what the answer SHOWED the reader. They come apart: the
    right page can be retrieved at rank 2, the model can cite the rank-1
    chunk instead, and a reader following the citation lands on the
    wrong page of a 4-page policy. Recall says 1.0, the citation is
    still wrong.

    None when the case expects no particular page (an `.md` corpus, or
    a case that does not pin one).
    """
    if not expect_pages:
        return None
    present = {p for p in cited_pages if p is not None}
    return all(page in present for page in expect_pages)


# ------------------------------------------------------------ aggregation --


@dataclass
class RetrievalSummary:
    """Aggregated retrieval metrics for one bucket of cases."""

    n: int = 0
    # Cases that label support. Only these contribute to recall/MRR.
    n_scored: int = 0
    recall_at_k: Optional[float] = None
    mrr: Optional[float] = None
    # Cases whose support was never retrieved at any rank. Listed, not
    # counted: a reader fixing retrieval needs the case ids, and a bare
    # count of 3 is not actionable.
    missed: list[str] = field(default_factory=list)
    # Retrieved, but below k -- so the prompt never saw it. These are
    # ranking failures rather than retrieval failures and have a
    # different fix (reranker, candidate count) than a miss does.
    below_k: list[str] = field(default_factory=list)
    citation_pages_ok: Optional[float] = None
    n_citation_scored: int = 0

    @property
    def small_n(self) -> bool:
        """Fewer than 8 scored cases: report, do not conclude."""
        return 0 < self.n_scored < 8


@dataclass(frozen=True)
class CaseRetrieval:
    """One case's retrieval outcome, as fed to the aggregator."""

    id: str
    recall: Optional[float]
    reciprocal_rank: Optional[float]
    first_rank: Optional[int]
    citation_pages_ok: Optional[bool] = None


def summarise_retrieval(cases: Sequence[CaseRetrieval], k: int) -> RetrievalSummary:
    summary = RetrievalSummary(n=len(cases))

    scored = [c for c in cases if c.recall is not None]
    summary.n_scored = len(scored)
    if scored:
        summary.recall_at_k = sum(c.recall for c in scored) / len(scored)
    summary.mrr = mean_reciprocal_rank(c.reciprocal_rank for c in cases)

    for case in scored:
        if case.first_rank is None:
            summary.missed.append(case.id)
        elif case.first_rank > k:
            summary.below_k.append(case.id)

    cited = [c for c in cases if c.citation_pages_ok is not None]
    summary.n_citation_scored = len(cited)
    if cited:
        summary.citation_pages_ok = sum(
            1 for c in cited if c.citation_pages_ok
        ) / len(cited)

    return summary
